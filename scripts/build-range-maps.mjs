import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { mapDrawing as draw, projectRange } from './map-projection.mjs';
import { sphericalGeometry } from './range-geometry.mjs';
import { validateRangeSources, validateRangeFeature } from './range-review.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const input = path.join(root, 'data/ranges');
const output = path.join(root, 'public/maps');
const read = async (name) =>
  JSON.parse(await readFile(path.join(input, name), 'utf8'));

const sources = await read('sources.json');
validateRangeSources(sources);
const reviewed = await Promise.all(
  sources.map(async (source) => ({
    source,
    geometry: validateRangeFeature(
      source,
      await readFile(path.join(input, `${source.id}.geojson`)),
    ),
  })),
);

const world = await read('world.geojson');
const land = world.features.map((f) => ({
  type: 'Feature',
  geometry: sphericalGeometry(f.geometry),
  properties: {},
}));
const basemap = {
  viewBox: [0, 0, 1000, 540],
  paths: land.map((f) => draw(f)),
};
async function save(name, data) {
  const body = JSON.stringify(data);
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 12);
  const filename = `${name}-${hash}.json`;
  await mkdir(output, { recursive: true });
  await writeFile(path.join(output, filename), body);
  return `/maps/${filename}`;
}
const basemapUrl = await save('world', basemap);
const manifest = {};
for (const { source, geometry } of reviewed) {
  const data = projectRange(geometry, source.focusBounds);
  manifest[source.id] = {
    url: await save(source.id, data),
    bounds: data.viewBox,
    taxonId: source.taxonId,
    scientificName: source.name,
    modelVersion: source.properties.geomodel_version,
    downloadedOn: source.downloadedOn,
    sourceUrl: source.url,
    datasetUrl: source.datasetUrl,
    licenseUrl: source.licenseUrl,
    referenceUrl: source.review.referenceUrl,
  };
}
await writeFile(
  path.join(root, 'lib/range-maps.ts'),
  `// Generated by scripts/build-range-maps.mjs from attributed geographic data.\n` +
    `export const rangeBasemapUrl = ${JSON.stringify(basemapUrl)};\n` +
    `export type RangeMapEntry = {url: string; bounds: [number, number, number, number]; taxonId: number; scientificName: string; modelVersion: string; downloadedOn: string; sourceUrl: string; datasetUrl: string; licenseUrl: string; referenceUrl: string};\n` +
    `export const rangeMaps: Partial<Record<string, RangeMapEntry>> = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(
  `Prepared ${Object.keys(manifest).length} range overlays with one shared Natural Earth basemap.`,
);
