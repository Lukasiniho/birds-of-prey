import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { geoNaturalEarth1, geoPath } from 'd3-geo';
import { sphericalGeometry } from './range-geometry.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const input = path.join(root, 'data/ranges');
const output = path.join(root, 'public/maps');
await mkdir(output, { recursive: true });
const read = async (name) =>
  JSON.parse(await readFile(path.join(input, name), 'utf8'));

const projection = geoNaturalEarth1().fitExtent(
  [
    [14, 14],
    [986, 526],
  ],
  { type: 'Sphere' },
);
const draw = geoPath(projection).digits(2);
const world = await read('world.geojson');
const land = world.features.map((f) => ({
  type: 'Feature',
  geometry: sphericalGeometry(f.geometry),
  properties: {},
}));
const basemap = {
  viewBox: [0, 0, 1000, 540],
  paths: land.map((f) => draw(f)),
};
async function save(name, data) {
  const body = JSON.stringify(data);
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 12);
  const filename = `${name}-${hash}.json`;
  await writeFile(path.join(output, filename), body);
  return `/maps/${filename}`;
}
const basemapUrl = await save('world', basemap);
const manifest = {};
for (const source of await read('sources.json')) {
  const feature = await read(`${source.id}.geojson`);
  if (
    feature.properties.name !== source.name ||
    feature.properties.taxon_id !== source.taxonId
  ) {
    throw new Error(`Taxon mismatch: ${source.id}`);
  }
  const geometry = sphericalGeometry(feature.geometry);
  const rangePath = draw(geometry);
  const [[left, top], [right, bottom]] = draw.bounds(geometry);
  if (!rangePath || ![left, top, right, bottom].every(Number.isFinite))
    throw new Error(`Invalid geometry: ${source.id}`);
  const width = Math.min(
    1000,
    Math.max(260, (right - left) * 1.18, (bottom - top) * 1.18 * 1.85),
  );
  const height = Math.min(540, width / 1.85);
  const x = Math.max(0, Math.min(1000 - width, (left + right - width) / 2));
  const y = Math.max(0, Math.min(540 - height, (top + bottom - height) / 2));
  const data = {
    path: rangePath,
    viewBox: [x, y, width, height].map((n) => +n.toFixed(2)),
  };
  manifest[source.id] = {
    url: await save(source.id, data),
    taxonId: source.taxonId,
    scientificName: source.name,
    modelVersion: feature.properties.geomodel_version,
  };
}
await writeFile(
  path.join(root, 'lib/range-maps.ts'),
  `// Generated by scripts/build-range-maps.mjs from attributed geographic data.\n` +
    `export const rangeBasemapUrl = ${JSON.stringify(basemapUrl)};\n` +
    `export const rangeMaps: Record<string, {url: string; taxonId: number; scientificName: string; modelVersion: string}> = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(
  `Prepared ${Object.keys(manifest).length} range overlays with one shared Natural Earth basemap.`,
);
