import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { projectRange } from './map-projection.mjs';
import {
  validateReferenceSources,
  validateReferenceFeature,
} from './reference-range-review.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const input = path.join(root, 'data/ranges/reference-vectors');
const sources = JSON.parse(
  await readFile(path.join(input, 'sources.json'), 'utf8'),
);
validateReferenceSources(sources);
// Validate the entire batch before writing any public artifacts.
const reviewed = await Promise.all(
  sources.map(async (source) => ({
    source,
    geometry: validateReferenceFeature(
      source,
      await readFile(path.join(input, `${source.id}.geojson`)),
    ),
  })),
);
const manifest = {};
for (const { source, geometry } of reviewed) {
  const range = projectRange(geometry, source.focusBounds);
  const body = JSON.stringify(range);
  const hash = createHash('sha256').update(body).digest('hex').slice(0, 12);
  const filename = `${source.id}-reference-${hash}.json`;
  await mkdir(path.join(root, 'public/maps'), { recursive: true });
  await writeFile(path.join(root, 'public/maps', filename), body);
  manifest[source.id] = {
    url: `/maps/${filename}`,
    bounds: range.viewBox,
    label: 'Verbreitung',
    sourceName: `Nach ${source.author}`,
    sourceUrl: source.sourceUrl,
    license: source.license,
    licenseUrl: source.licenseUrl,
    note: source.note,
  };
}
await writeFile(
  path.join(root, 'lib/reference-range-maps.ts'),
  `// Generated by scripts/build-reference-range-maps.mjs.\n` +
    `import type { DisplayRangeMapEntry } from './range-map-entry';\n` +
    `export const referenceRangeMaps: Partial<Record<string, DisplayRangeMapEntry>> = ${JSON.stringify(manifest, null, 2)};\n`,
);
console.log(
  `Prepared ${reviewed.length} licensed reference overlays in the shared basemap projection.`,
);
