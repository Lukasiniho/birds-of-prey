import sharp from 'sharp';
import fs from 'node:fs/promises';
import crypto from 'node:crypto';
const generated=process.argv[2];
if(!generated)throw new Error('Pass generated source');
const original='public/birds/portrait-kronenadler-20260913-v4.png';
const output='public/birds/portrait-kronenadler-20260913-v5.png';
const reference='public/birds/kronenadler-20260913-v3.png';
const root='output/imagegen/kronenadler-portrait-dark-20260913/';
const a=await sharp(original).ensureAlpha().raw().toBuffer({resolveWithObject:true});
const b=await sharp(output).ensureAlpha().raw().toBuffer({resolveWithObject:true});
let alphaIdentical=true;for(let i=3;i<a.data.length;i+=4)if(a.data[i]!==b.data[i])alphaIdentical=false;
if(!alphaIdentical)throw new Error('Alpha changed');
const report={original,generated,output,reference,referenceRole:'Adult head/neck plumage color only',method:'Built-in imagegen recolor; original alpha restored locally with scripts/restore-bird-alpha.mjs; feather-edge RGB cleanup, no resizing of the final canvas or neck distortion.',canvas:[a.info.width,a.info.height],alphaIdentical,prompt:root+'final-prompt.txt',discarded:'Earlier generation used v3 before concurrent v4 neck correction arrived; not integrated.'};
for(const [key,p]of Object.entries({original,generated,output,reference}))report[key+'Sha256']=crypto.createHash('sha256').update(await fs.readFile(p)).digest('hex');
await fs.writeFile(root+'verification.json',JSON.stringify(report,null,2)+'\n');
const panels=[];for(let row=0;row<2;row++)for(let col=0;col<3;col++)panels.push({input:await sharp([original,output][row]).resize(320,320).flatten({background:['#f5f9fa','#15252d','#557d77'][col]}).png().toBuffer(),left:col*320,top:row*320});
await sharp({create:{width:960,height:640,channels:3,background:'#f5f9fa'}}).composite(panels).png().toFile(root+'comparison.png');
console.log(report);
